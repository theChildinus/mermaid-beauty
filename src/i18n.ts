export type LanguageSetting = 'auto' | 'en' | 'zh';
export type UiLanguage = 'en' | 'zh';

export function resolveLanguage(language: LanguageSetting, obsidianLanguage: string): UiLanguage {
  return language === 'auto' ? (/^zh(?:[-_]|$)/i.test(obsidianLanguage) ? 'zh' : 'en') : language;
}

