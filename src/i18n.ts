export type UiText = keyof typeof chinese;
export function translate(language: UiLanguage, text: UiText, values: Record<string, string> = {}): string {
  const template = language === 'zh' ? chinese[text] : text;
  return template.replace(/\{(\w+)\}/g, (match, key: string) => values[key] ?? match);
}
